const aliases = {
  "pok-mon": "pokemon",
};

export function getTheme(themeKey) {
  if (typeof themeKey !== "string") return null;
  const key = aliases[themeKey.toLowerCase()] || themeKey.toLowerCase();
  return themes[key] || null;
}
